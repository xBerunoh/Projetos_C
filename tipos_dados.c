#include <stdio.h>

int main(){
    int numero = 10;
    float numeroQuebrado = 12.5;
    char letra = 'A';
    char nome[6] = "Bruno";

    printf("Numero: %d\n",numero);
    printf("Numero decimal: %0.4f\n",numeroQuebrado);
    printf("Letra: %c\n",letra);
    printf("Nome: %s \n",nome);
    return 0;
}